import { IdCard } from "lucide-react";
import { FormEvent, useEffect, useState } from "react";
import { executeDynamicMutation } from "../../api/lookups";
import { AutoDismissAlert } from "../../components/ui/AutoDismissAlert";
import { Input } from "../../components/ui/Input";
import { useAuth } from "../../state/AuthContext";
import type { LucideIcon } from "lucide-react";

export type TProductType = {
  prodtype_code?: string;
  prodtype_name?: string;
};

type FormMode = "add" | "edit" | "view";

type Props = {
  mode: FormMode;
  existingData?: Partial<TProductType>;
  onClose: (shouldRefetch?: boolean) => void;
  onSavingChange?: (saving: boolean) => void;
};

const EMPTY: TProductType = {
  prodtype_code: "",
  prodtype_name: "",
};

/* ─────────────────────────────────────────────────────────────
   SectionPanel — EXACT Freight structure (from WMS)
   ───────────────────────────────────────────────────────────── */
function SectionPanel({
  title,
  icon: Icon,
  children,
}: {
  title: string;
  icon: LucideIcon;
  children: React.ReactNode;
}) {
  return (
    <section className="freight-panel overflow-hidden rounded-md border bg-background shadow-sm">
      <div className="freight-panel-title flex items-center justify-between gap-2 border-b bg-muted/35 px-3 py-2">
        <div className="flex min-w-0 items-center gap-2">
          <span className="freight-section-icon">
            <Icon size={16} />
          </span>
          <div className="min-w-0">
            <h3 className="m-0 truncate text-[11px] font-semibold text-foreground">{title}</h3>
          </div>
        </div>
      </div>
      <div className="freight-panel-body p-3">{children}</div>
    </section>
  );
}

/* ─────────────────────────────────────────────────────────────
   Field — matches WmsMasterForm / Freight label styling
   ───────────────────────────────────────────────────────────── */
function Field({
  label,
  required,
  children,
  className,
}: {
  label: string;
  required?: boolean;
  children: React.ReactNode;
  className?: string;
}) {
  return (
    <label className={`freight-field-label group flex flex-col gap-0.5 ${className ?? ""}`}>
      <span className="text-[11px] font-medium text-muted-foreground group-focus-within:text-primary transition-colors">
        {label}
        {required && <strong className="text-destructive ml-0.5 font-bold"> *</strong>}
      </span>
      {children}
    </label>
  );
}

export function AddProductTypeForm({ mode, existingData, onClose, onSavingChange }: Props) {
  const { user } = useAuth();
  const readonly = mode === "view";
  const isEdit = mode === "edit";

  // prodtype_code is auto-generated by the backend on add.
  // It is kept in state (not shown) only so edit can send it back as the key.
  const [form, setForm] = useState<TProductType>({ ...EMPTY });
  const [errors, setErrors] = useState<Partial<Record<keyof TProductType, string>>>({});
  const [apiError, setApiError] = useState("");

  useEffect(() => {
    if ((isEdit || readonly) && existingData) {
      setForm({
        ...EMPTY,
        prodtype_code: (existingData as any).PRODTYPE_CODE ?? existingData.prodtype_code ?? "",
        prodtype_name: (existingData as any).PRODTYPE_NAME ?? existingData.prodtype_name ?? "",
      });
    }
  }, [isEdit, readonly, existingData]);

  const set = (field: keyof TProductType, value: unknown) =>
    setForm((prev) => ({ ...prev, [field]: value }));

  const validate = (): boolean => {
    const next: Partial<Record<keyof TProductType, string>> = {};
    if (!form.prodtype_name?.trim()) next.prodtype_name = "Prod Type Name is required";
    setErrors(next);
    return Object.keys(next).length === 0;
  };

  // val1s1 = company_code, val1s2 = prodtype_code ("" on add -> auto-generated), val1s3 = prodtype_name
  const handleSubmit = async (event: FormEvent) => {
    event.preventDefault();
    if (readonly) return;
    if (!validate()) return;

    onSavingChange?.(true);
    setApiError("");
    try {
      await executeDynamicMutation({
        parameter: "PURCHASE_SALE_MSE_PRODTYPE",
        loginid: user?.loginid ?? "",
        val1s1: user?.company_code ?? "",
        val1s2: isEdit ? form.prodtype_code ?? "" : "",
        val1s3: form.prodtype_name?.trim() ?? "",
      });
      onClose(true);
    } catch (error) {
      setApiError(error instanceof Error ? error.message : "Unable to save product type");
    } finally {
      onSavingChange?.(false);
    }
  };

  return (
    <form className="grid content-start gap-4" id="product-type-form" onSubmit={handleSubmit}>
      <AutoDismissAlert
        notice={apiError ? { type: "error", message: apiError } : null}
        onClose={() => setApiError("")}
      />

      <SectionPanel title="Basic Information" icon={IdCard}>
        <div className="grid grid-cols-1 gap-3 md:grid-cols-2">
          <Field label="Prod Type Name" required>
            <Input
              disabled={readonly}
              placeholder="e.g. Electronics"
              value={form.prodtype_name ?? ""}
              onChange={(e) => set("prodtype_name", e.target.value)}
              className={errors.prodtype_name ? "border-destructive focus-visible:ring-destructive" : ""}
            />
            {errors.prodtype_name && (
              <span className="mt-0.5 text-[10px] font-medium text-destructive">{errors.prodtype_name}</span>
            )}
          </Field>
        </div>
      </SectionPanel>
    </form>
  );
}