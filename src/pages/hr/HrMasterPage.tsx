/** HR fields use exactly the same field definition as the WMS masters. */
export type HrMasterField = {
  name: string;
  label: string;
  required?: boolean;
  hideOnAdd?: boolean;
  disabledOnEdit?: boolean;
  disabledWhen?: (form: Record<string, unknown>) => boolean;
  onValueChange?: (value: unknown, form: Record<string, unknown>) => Record<string, unknown>;
  autoGenerated?: boolean;
  placeholder?: string;
  helperText?: string;
  type?: "text" | "number" | "select" | "email" | "textarea" | "checkbox" | "date" | "combobox";
  options?: { label: string; value: string }[];
  dropdownParam?: string;
  dropdownLabelKey?: string;
  dropdownValueKey?: string;
  dropdownDisplayFields?: string[];
  dropdownDisplaySeparator?: string;
  dropdownCodeMap?: Record<string, string>;
  filterDependsOn?: string;
  asyncOptions?: {
    endpoint: string;
    labelKey: string;
    valueKey: string;
    dependsOn?: string;
  };
  tab?: string;
  section?: string;
  table?: boolean;
  width?: number;
  colSpan?: number;
  align?: "left" | "center" | "right";
  min?: number;
  maxLength?: number;
  /** Disable the field when the form is in "add" mode */
  disabledOnAdd?: boolean;

  /** Lookup configuration (used by LookupField) */
  lookup?: {
    columns: Array<{ field: string; header: string; width?: number }>;
    valueField: string;
    displayFields: string[];
    loadOptions: (context?: any) => Promise<any[]>;
  };
};;

export type HrMasterConfig = {
  title: string;
  subtitle: string;
  master: string;
  gmEndpoint: string;
  routeKeys?: string[];
  keyField: string;
  /** Backend report URL, e.g. "/hr/reports/designation". When set, Print opens this report. */
  reportEndpoint?: string;
  fields: HrMasterField[];
  defaults?: Record<string, unknown>;
  deleteMode?: "master" | "gm" | "disabled";
  source?: "hr" | "dynamic" | "finance";
  mutationMode?: "common" | "column90";
  listQuery?: (context: HrMasterContext) => DynamicQueryParams;
  buildSave?: (form: Record<string, unknown>, context: HrMasterContext) => DynamicMutationParams | Record<string, unknown>;
  buildDelete?: (row: Record<string, unknown>, context: HrMasterContext) => DynamicDeleteParams;
  financeSaveEndpoint?: string;
  autoGenerateKey?: boolean;
  stripEditKeyOnSave?: boolean;
  /** When set, an "Import" button appears next to Add and opens the EDI import page for this key (e.g. "BANK"). */
  ediKey?: string;
  /** Saves the validated import rows. Without it, the import page validates only. */
  ediSubmit?: (rows: Record<string, string | null>[], context: HrMasterContext) => Promise<void>;
};

export type HrMasterContext = {
  loginid: string;
  companyCode: string;
  editMode: boolean;
  rows: Record<string, unknown>[];
  form?: Record<string, unknown>;
};

type Notice = { type: "success" | "error"; message: string } | null;

const FORM_ID = "hr-master-form";

/** DB "value too large" error -> friendly message. */
function friendlyDbError(message: string): string {
  const m = message.match(/\(actual:\s*(\d+),\s*maximum:\s*(\d+)\)/i);
  if (m) return `A field is too long (entered ${m[1]}, maximum ${m[2]} characters). Please shorten it.`;
  return message || "Unable to save. Please check the entered values.";
}

